d1 <- data.frame(ID = c(101, 102, 103), sex = c("F", "F", "M"), age = c(50, 60, 70))
d2 <- data.frame(ID = c(101, 101, 103, 103, 104), hgb = c(12, 11, 10, 9, 8))
merge(d1, d2)             # IDs present in both (inner join)
merge(d1, d2, all.x = TRUE)   # all IDs of the left table (left join)
merge(d1, d2, all.y = TRUE)   # all IDs of the right table (right join)
merge(d1, d2, all = TRUE)     # IDs present in either (full join)
