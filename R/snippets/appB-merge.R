d1 <- data.frame(ID = c(101, 102, 103), sex = c("F", "F", "M"), age = c(50, 60, 70))
d2 <- data.frame(ID = c(101, 101, 103, 103, 104), hgb = c(12, 11, 10, 9, 8))
merge(d1, d2)             # 양쪽에 모두 있는 ID (inner join)
merge(d1, d2, all.x = TRUE)   # 왼쪽 테이블 ID 모두 (left join)
merge(d1, d2, all.y = TRUE)   # 오른쪽 테이블 ID 모두 (right join)
merge(d1, d2, all = TRUE)     # 어느 한 쪽에라도 있으면 (full join)
