d0 <- c(196, 51, 244, 207, 56, 420, 146, 151, 340, 132, 382, 31, 366, 241, 294,
        166, 127, 286, 390, 361)
n <- length(d0)

th1 <- mean(d0) * 2 - 1;  th1                      # 457.7
sd1 <- sqrt((th1^2 - 1) / (3 * n));  sd1           #  59.08867
ci1 <- th1 + c(-1, 1) * qt(0.975, n - 1) * sd1;  ci1   # 334.026 581.374

Yn  <- max(d0)
th2 <- Yn * (n + 1) / n;  th2                      # 441
sd2 <- sqrt(th2^2 / (n * (n + 2)));  sd2           #  21.02385
ci2 <- th2 + c(-1, 1) * qt(0.975, n - 1) * sd2;  ci2   # 396.9966 485.0034
